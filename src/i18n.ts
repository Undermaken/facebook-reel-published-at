export type Language = 'en' | 'it' | 'es' | 'de' | 'fr';

export function resolveLocale(raw = navigator.language): {
  language: Language;
  locale: string;
} {
  try {
    const parsed = new Intl.Locale(raw);
    if (['en', 'it', 'es', 'de', 'fr'].includes(parsed.language)) {
      return { language: parsed.language as Language, locale: parsed.toString() };
    }
  } catch {
    /* Invalid browser language values use the English fallback. */
  }
  return { language: 'en', locale: 'en' };
}

